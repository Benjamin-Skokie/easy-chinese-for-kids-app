import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const contentRoot = join(repoRoot, "culture", "content");
const outputFile = join(repoRoot, "about", "sources-research", "culture-sources.js");

const categoryNames = {
  architecture: "Architecture",
  art: "Art",
  clothing: "Clothing",
  culture: "Culture & Daily Life",
  economy: "Economy & Exchange",
  figures: "People",
  food: "Food",
  "folk-customs": "Festivals & Customs",
  "folk-tales": "Folk Tales",
  geography: "Geography",
  inventions: "Inventions & Technology",
  literature: "Literature",
  military: "Military History & Technology",
  philosophy: "Philosophy",
  politics: "Government & Society",
  religion: "Religion & Belief"
};

function walk(directory) {
  return readdirSync(directory).flatMap((name) => {
    const path = join(directory, name);
    return statSync(path).isDirectory() ? walk(path) : [path];
  });
}

function decodeHtml(text) {
  return text
    .replace(/<[^>]+>/g, " ")
    .replace(/&amp;/g, "&")
    .replace(/&quot;/g, '"')
    .replace(/&#39;|&apos;/g, "'")
    .replace(/&mdash;/g, "—")
    .replace(/&ndash;/g, "–")
    .replace(/\s+/g, " ")
    .trim();
}

function storyTitles(category, slug) {
  const pagePath = join(repoRoot, "culture", "books", category, slug, "index.html");
  try {
    const html = readFileSync(pagePath, "utf8");
    const h1 = html.match(/<h1[^>]*>([\s\S]*?)<\/h1>/i)?.[1];
    const afterH1 = h1 ? html.slice(html.indexOf(h1) + h1.length) : html;
    const h2 = afterH1.match(/<h2[^>]*>([\s\S]*?)<\/h2>/i)?.[1];
    return {
      zh: decodeHtml(h1 ?? html.match(/<title>([\s\S]*?)<\/title>/i)?.[1] ?? slug),
      en: h2 ? decodeHtml(h2) : ""
    };
  } catch {
    return { zh: slug.split("-").map((word) => word[0]?.toUpperCase() + word.slice(1)).join(" "), en: "" };
  }
}

function sourceGroups(markdown) {
  const groups = [];
  let group = null;
  let pendingLabel = "";

  const ensureGroup = () => {
    if (!group) {
      group = { title: "General references", sources: [] };
      groups.push(group);
    }
    return group;
  };

  for (const rawLine of markdown.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line) continue;

    const heading = line.match(/^##\s+(.+)/)?.[1]?.replace(/^\d+\.\s*/, "").trim();
    if (heading) {
      if (/^(?:image|visual) (?:audit|boundaries|notes)|^activity boundaries/i.test(heading)) break;
      group = { title: heading, sources: [] };
      groups.push(group);
      pendingLabel = "";
      continue;
    }

    const sourceLabel = line.match(/^Source:\s*(.+)/i)?.[1];
    if (sourceLabel) {
      pendingLabel = sourceLabel.replace(/\*+/g, "").trim();
      continue;
    }

    const markdownLink = line.match(/^-?\s*\[([^\]]+)\]\((https?:\/\/[^)]+)\)/);
    if (markdownLink) {
      ensureGroup().sources.push({ label: markdownLink[1], url: markdownLink[2] });
      continue;
    }

    const urlMatch = line.match(/^(?:-\s*)?(?:URL|DOI):?\s*(https?:\/\/\S+)/i)
      ?? line.match(/^(?:-\s*)?(https?:\/\/\S+)/i);
    if (urlMatch) {
      const url = urlMatch[1].replace(/[),.;]+$/, "");
      let fallback = "Research source";
      try { fallback = new URL(url).hostname.replace(/^www\./, ""); } catch {}
      ensureGroup().sources.push({ label: pendingLabel || fallback, url });
      if (!/^DOI:/i.test(line)) pendingLabel = "";
    }
  }

  return groups.filter((entry) => entry.sources.length);
}

const stories = walk(contentRoot)
  .filter((path) => path.endsWith("references.md"))
  .map((path) => {
    const [category, slug] = relative(contentRoot, dirname(path)).split("/");
    const titles = storyTitles(category, slug);
    return {
      category,
      categoryName: categoryNames[category] ?? category,
      slug,
      title: titles.zh,
      titleEn: titles.en,
      storyPath: `../../culture/books/${category}/${slug}/`,
      groups: sourceGroups(readFileSync(path, "utf8"))
    };
  })
  .sort((a, b) => a.categoryName.localeCompare(b.categoryName) || a.title.localeCompare(b.title));

writeFileSync(
  outputFile,
  `// Generated by scripts/build_sources_research.mjs.\nwindow.NIHAO_CULTURE_SOURCES = ${JSON.stringify(stories, null, 2)};\n`
);

console.log(`Wrote ${stories.length} culture-story source records to ${relative(repoRoot, outputFile)}.`);
