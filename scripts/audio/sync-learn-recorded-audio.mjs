import { createHash } from "node:crypto";
import { access, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { learnAudioEntries } from "../../src/data/learn-audio-manifest.js";

const projectRoot = path.resolve(import.meta.dirname, "../..");
const audioDirectory = path.join(projectRoot, "assets/audio/learn");
const outputPath = path.join(projectRoot, "src/data/learn-recorded-audio.js");

async function exists(filePath) {
  try {
    await access(filePath);
    return true;
  } catch {
    return false;
  }
}

const readyIds = [];
const assetVersionHash = createHash("sha256");
for (const entry of learnAudioEntries) {
  const audioPath = path.join(audioDirectory, `${entry.id}.mp3`);
  if (await exists(audioPath)) {
    readyIds.push(entry.id);
    assetVersionHash.update(entry.id);
    assetVersionHash.update(await readFile(audioPath));
  }
}
const recordedLearnAudioVersion = assetVersionHash.digest("hex").slice(0, 12);

await writeFile(outputPath, `// Generated by scripts/audio/sync-learn-recorded-audio.mjs. Do not edit by hand.\nexport const recordedLearnAudioVersion = "${recordedLearnAudioVersion}";\nexport const recordedLearnAudioIds = new Set(${JSON.stringify(readyIds, null, 2)});\n`);
console.log(`Recorded Learn audio: ${readyIds.length}/${learnAudioEntries.length} assets are ready (v=${recordedLearnAudioVersion}).`);
