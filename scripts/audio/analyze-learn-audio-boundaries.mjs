import { readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { spawn } from "node:child_process";
import { measuredBoundarySilenceMsById as existingMeasurements } from "../../src/core/recorded-audio-boundaries.js";

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const audioDirectory = path.join(projectRoot, "assets/audio/learn");
const outputPath = path.join(projectRoot, "src/core/recorded-audio-boundaries.js");
const thresholdDb = -45;
const concurrency = 12;
const onlyArgument = process.argv.find((argument) => argument.startsWith("--only="));
const selectedIds = new Set(onlyArgument?.slice("--only=".length).split(",").filter(Boolean) ?? []);

function run(command, args) {
  return new Promise((resolve, reject) => {
    const child = spawn(command, args, { stdio: ["ignore", "pipe", "pipe"] });
    let stdout = "";
    let stderr = "";
    child.stdout.setEncoding("utf8");
    child.stderr.setEncoding("utf8");
    child.stdout.on("data", (chunk) => { stdout += chunk; });
    child.stderr.on("data", (chunk) => { stderr += chunk; });
    child.on("error", reject);
    child.on("close", (code) => code === 0 ? resolve({ stdout, stderr }) : reject(new Error(`${command} failed (${code}): ${stderr}`)));
  });
}

async function inspectAudio(fileName) {
  const filePath = path.join(audioDirectory, fileName);
  const [durationOutput, silenceOutput] = await Promise.all([
    run("ffprobe", ["-v", "error", "-show_entries", "format=duration", "-of", "default=noprint_wrappers=1:nokey=1", filePath]),
    run("ffmpeg", ["-hide_banner", "-i", filePath, "-af", `silencedetect=noise=${thresholdDb}dB:d=0.015`, "-f", "null", "-"])
  ]);
  const durationMs = Math.round(Number(durationOutput.stdout.trim()) * 1000);
  const starts = [...silenceOutput.stderr.matchAll(/silence_start: ([0-9.]+)/gu)].map((match) => Number(match[1]) * 1000);
  const ends = [...silenceOutput.stderr.matchAll(/silence_end: ([0-9.]+)/gu)].map((match) => Number(match[1]) * 1000);
  const leading = starts[0] === 0 && ends.length ? Math.round(ends[0]) : 0;
  const trailingStart = starts.at(-1);
  const trailing = Number.isFinite(trailingStart) && trailingStart > 0 ? Math.max(0, Math.round(durationMs - trailingStart)) : 0;
  return [fileName.slice(0, -4), { leading, trailing }];
}

const allFiles = (await readdir(audioDirectory)).filter((file) => /^[a-f0-9]{12}\.mp3$/u.test(file)).sort();
const files = selectedIds.size
  ? allFiles.filter((file) => selectedIds.has(file.slice(0, -4)))
  : allFiles;
if (selectedIds.size && files.length !== selectedIds.size) {
  const presentIds = new Set(files.map((file) => file.slice(0, -4)));
  throw new Error(`Unknown Learn recording id(s): ${[...selectedIds].filter((id) => !presentIds.has(id)).join(", ")}`);
}
const results = [];
let nextIndex = 0;

await Promise.all(Array.from({ length: Math.min(concurrency, files.length) }, async () => {
  while (nextIndex < files.length) {
    const file = files[nextIndex];
    nextIndex += 1;
    results.push(await inspectAudio(file));
  }
}));

const measuredBoundarySilenceMsById = Object.fromEntries([
  ...Object.entries(existingMeasurements),
  ...results
].sort(([a], [b]) => a.localeCompare(b)));
const generated = `// Generated by scripts/audio/analyze-learn-audio-boundaries.mjs. Do not edit by hand.\n// ${Object.keys(measuredBoundarySilenceMsById).length} Learn recordings measured at ${thresholdDb} dBFS with a 15 ms minimum silence span.\nexport const measuredBoundarySilenceMsById = Object.freeze(${JSON.stringify(measuredBoundarySilenceMsById, null, 2)});\n\nexport const recordedAudioBoundaryIds = new Set(Object.keys(measuredBoundarySilenceMsById));\nexport const standaloneBoundarySilenceMs = 100;\nexport const sequenceBoundarySilenceMs = 60;\n\nexport function recordedAudioPlaybackWindow(source, retainedSilenceMs = standaloneBoundarySilenceMs) {\n  const id = /\\/([a-f0-9]{12})\\.mp3(?:$|[?])/u.exec(String(source ?? \"\"))?.[1];\n  const silence = measuredBoundarySilenceMsById[id];\n  if (!silence) return null;\n  return {\n    startOffsetMs: Math.max(0, silence.leading - retainedSilenceMs),\n    endOffsetMs: Math.max(0, silence.trailing - retainedSilenceMs)\n  };\n}\n`;
await writeFile(outputPath, generated);
console.log(`Measured ${files.length} Learn recordings with ${concurrency} workers.`);
