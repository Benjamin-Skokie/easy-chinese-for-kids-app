import { createHash } from "node:crypto";
import { readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { pathToFileURL } from "node:url";

const projectRoot = path.resolve(import.meta.dirname, "../..");
const featuresRoot = path.join(projectRoot, "src/features");
const outputPath = path.join(projectRoot, "src/data/learn-audio-manifest.js");

function isDataModule(filePath) {
  const relative = path.relative(featuresRoot, filePath).replaceAll(path.sep, "/");
  return relative.endsWith(".js")
    && !relative.includes("/pinyin")
    && (!relative.endsWith("-runtime.js") || relative === "play-hobbies/play-hobbies-runtime.js")
    && !relative.endsWith("-controller.js")
    && !relative.endsWith("/state.js");
}

async function featureModules(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const nested = await Promise.all(entries.map(async (entry) => {
    const entryPath = path.join(directory, entry.name);
    if (entry.isDirectory()) return featureModules(entryPath);
    return isDataModule(entryPath) ? [entryPath] : [];
  }));
  return nested.flat();
}

function addEntries(value, source, entries, visited = new WeakSet(), parentKey = "") {
  if (!value || typeof value !== "object") return;
  if (visited.has(value)) return;
  visited.add(value);

  if (typeof value.audio === "string" && value.audio.trim()) {
    entries.push({
      text: value.audio.trim(),
      pinyin: typeof value.pinyin === "string" ? value.pinyin.trim() : "",
      source
    });
  }

  // Most vocabulary cards are spoken by their `hanzi` field, while scene
  // players speak every individual object in `lines`. Include only authored
  // Chinese items that also carry a pinyin reading; this avoids recording UI
  // headings, but covers the exact text learners can tap to hear.
  if (
    typeof value.hanzi === "string"
    && value.hanzi.trim()
    && typeof value.pinyin === "string"
    && value.pinyin.trim()
  ) {
    entries.push({
      text: value.hanzi.trim(),
      pinyin: value.pinyin.trim(),
      source
    });
  }

  if (Array.isArray(value)) {
    value.forEach((item) => addEntries(item, source, entries, visited, parentKey));
    return;
  }
  Object.entries(value).forEach(([key, item]) => addEntries(item, source, entries, visited, key));
}

const modules = await featureModules(featuresRoot);
modules.push(path.join(projectRoot, "src/data/topic-registry.js"));

const rawEntries = [];
for (const modulePath of modules.sort()) {
  const exports = await import(pathToFileURL(modulePath));
  Object.values(exports).forEach((value) => addEntries(value, path.relative(projectRoot, modulePath), rawEntries));
}

const entriesByText = new Map();
rawEntries.forEach((entry) => {
  const existing = entriesByText.get(entry.text);
  if (existing) {
    existing.sources.add(entry.source);
    if (entry.pinyin) existing.pinyins.add(entry.pinyin);
    return;
  }
  entriesByText.set(entry.text, { ...entry, sources: new Set([entry.source]), pinyins: new Set(entry.pinyin ? [entry.pinyin] : []) });
});

const ambiguous = [];
const entries = [...entriesByText.values()].map(({ text, pinyins, sources }) => {
  const readings = [...pinyins].sort();
  if (readings.length > 1) ambiguous.push({ text, readings });
  // A repeated audio text sometimes appears inside a longer phrase, where its
  // surrounding object carries a different (or incomplete) pinyin field.
  // Do not feed conflicting metadata to TTS; the Chinese text remains the
  // reliable generation input and exceptional pronunciations can be reviewed.
  const pinyin = readings.length === 1 ? readings[0] : "";
  const id = createHash("sha256").update(`${text}\u0000${pinyin}`).digest("hex").slice(0, 12);
  return { id, text, pinyin, pinyinOptions: readings, sources: [...sources].sort() };
}).sort((a, b) => a.text.localeCompare(b.text, "zh-Hans-CN"));

const version = createHash("sha256").update(JSON.stringify(entries)).digest("hex").slice(0, 12);
const output = `// Generated by scripts/audio/build-learn-audio-manifest.mjs. Do not edit by hand.\nexport const learnAudioVersion = "${version}";\n\nexport const learnAudioEntries = ${JSON.stringify(entries, null, 2)};\n`;
await writeFile(outputPath, output);

console.log(`Learn audio manifest: ${entries.length} unique entries from ${rawEntries.length} occurrences in ${modules.length} data modules.`);
if (ambiguous.length) {
  console.warn(`Pinyin conflicts (${ambiguous.length}):`);
  ambiguous.forEach(({ text, readings }) => console.warn(`  ${text}: ${readings.join(" | ")}`));
}
